"""
make_k2b_pairs_table.py
=======================
Recovery of the switching cost by source pair in simulated data (K2b): the table of the four fits
in Rout/k2b_pix_change.csv (Kappa agent, diag_k2_nls_simulation.py), two simulated worlds (fe:
the paper's fixed effects; ideal) by two versions of the Pix change (before-after; dose), each the
pooled-weight, split-model row, and the true values the simulation was built on.

Columns: kappa (level) and its Pix change for the savings, checking and time-deposit pairs, the
dose coefficient (kappa_U) for the savings pair, and whether the fit converged. Standard errors in
parentheses under the savings columns only. A checking cell whose parameter sits at the
optimizer's box (column at_box) prints "at bound". Three decimals.

Outputs
  Drafts/Deposit Competition/tab_k2b_pairs.tex   tabular only (booktabs); the paper wraps it
  Drafts/Deposit Competition/tab_k2b_pairs.md    the same table in markdown
The numbers have keys kappa.k2b.* (make_paper_numbers.py, collect_k2b).

Usage:  python make_k2b_pairs_table.py
"""
from utils.venv_guard import ensure_project_venv
ensure_project_venv(__file__)

import sys

import pandas as pd

from utils import paths as _paths

SRC = _paths.rout_dir() / "k2b_pix_change.csv"
TEX = _paths.drafts_dir() / "tab_k2b_pairs.tex"
MD = _paths.drafts_dir() / "tab_k2b_pairs.md"
FITS = (("FE, before-after", "fe", "before_after"), ("FE, dose", "fe", "dose"),
        ("Ideal, before-after", "ideal", "before_after"), ("Ideal, dose", "ideal", "dose"))
MINUS = "$-$"


def num(x) -> str:
    """Three decimals, a math minus, never -0.000; '' for a missing value."""
    if x is None or pd.isna(x):
        return ""
    s = f"{float(x):.3f}"
    if s.startswith("-"):
        s = s[1:] if float(s) == 0.0 else MINUS + s[1:]
    return s


def se(x) -> str:
    return f"({num(x)})" if x is not None and not pd.isna(x) else ""


def rows(d: pd.DataFrame) -> list:
    """[(label, cells, se_cells)] per fit, then the truth row."""
    out = []
    for label, world, version in FITS:
        r = d[(d["world"] == world) & (d["version"] == version) & (d["weight"] == "pool")
              & (d["model"] == "split")]
        if len(r) != 1:
            raise SystemExit(f"{SRC.name}: {len(r)} rows for {world}/{version}/pool/split")
        r = r.iloc[0]
        dose = version == "dose"
        boxed = set(str(r["at_box"]).split(";")) if pd.notna(r["at_box"]) else set()
        chk = ["at bound" if "kappa_chk" in boxed else num(r["kappa_chk"]),
               "at bound" if "dkappa_chk" in boxed else num(r["dkappa_chk"])]
        cells = [num(r["kappa"]), num(r["dkappa"]), num(r["kappa_U"]) if dose else "",
                 *chk, num(r["kappa_td"]), num(r["dkappa_td"]), "yes" if r["converged"] else "no"]
        ses = [se(r["se_kappa"]), se(r["se_dkappa"]), se(r["se_kappa_U"]) if dose else "",
               "", "", "", "", ""]
        out.append((label, cells, ses))
    t = d.iloc[0]
    truth = [num(t["kappa0_true"]), num(t["dkappa_true"]),
             num(d.loc[d["version"] == "dose", "kappa_U_true"].iloc[0]),
             num(t["kappa0_true"]), num(t["dkappa_true"]), num(t["kappa0_true"]),
             num(t["dkappa_true"]), ""]
    out.append(("Truth", truth, None))
    return out


def render_tex(body: list) -> str:
    lines = [
        "% tab_k2b_pairs.tex -- GENERATED by make_k2b_pairs_table.py. Do not edit.",
        "% Tabular only (needs booktabs): the paper wraps it in its own table, caption and notes.",
        "% Source: Rout/k2b_pix_change.csv (pooled weights, split model). Keys: \\pn{kappa.k2b.*}.",
        "% Nine columns fit the text width at 4pt column spacing (set inside the wrapper's group).",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}lrrrrrrrc@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Savings} & \multicolumn{2}{c}{Checking} & "
        r"\multicolumn{2}{c}{Time deposit} & \\",
        r"\cmidrule(lr){2-4} \cmidrule(lr){5-6} \cmidrule(lr){7-8}",
        r"Fit & Level & Change & Dose & Level & Change & Level & Change & Conv. \\",
        r"\midrule",
    ]
    for label, cells, ses in body:
        if label == "Truth":
            lines.append(r"\midrule")
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")
        if ses and any(ses):
            lines.append(" & " + " & ".join(ses) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def render_md(body: list) -> str:
    out = ["<!-- GENERATED by make_k2b_pairs_table.py. Do not edit. -->", "",
           "| Fit | Savings level | Savings change | Savings dose | Checking level | "
           "Checking change | Time-deposit level | Time-deposit change | Converged |",
           "|---|---|---|---|---|---|---|---|---|"]
    for label, cells, ses in body:
        out.append(f"| {label} | " + " | ".join(c.replace(MINUS, "−") for c in cells) + " |")
        if ses and any(ses):
            out.append("| | " + " | ".join(c.replace(MINUS, "−") for c in ses) + " |")
    return "\n".join(out) + "\n"


def main() -> int:
    if not SRC.is_file():
        print(f"{SRC} not found: run the Kappa agent's K2b step first.")
        return 1
    body = rows(pd.read_csv(SRC))
    TEX.write_text(render_tex(body), encoding="utf-8", newline="\n")
    MD.write_text(render_md(body), encoding="utf-8", newline="\n")
    print(f"  wrote {TEX}\n  wrote {MD}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
