# 3. Cluster Diagnostics LaTeX Block Builder
# ==============================================================================
def build_cluster_diagnostics_tex(df):
    """
    Computes cluster imbalance statistics and returns a formatted LaTeX block
    containing a summary table of the diagnostics.

    Parameters
    ----------
    df : pandas DataFrame
        The estimation-ready panel (output of estimation_1_sleep.build_data).

    Returns
    -------
    str : LaTeX fragment.
    """
    cluster_var = 'CodConglomeradoPrudencial'
    Ns       = df.groupby(cluster_var).size()
    G        = len(Ns)
    mean_Ng  = float(np.mean(Ns))
    std_Ng   = float(np.std(Ns, ddof=0))
    cv       = std_Ng / mean_Ng if mean_Ng > 0 else 0
    G_star   = max(1.0, G / (1 + cv ** 2))
    total    = len(df)

    top5 = Ns.sort_values(ascending=False).head(5)
    top5_rows = '\n'.join(
        f"    {c} & {n:,} & {(n / total) * 100:.1f}\\% \\\\"
        for c, n in top5.items()
    )

    block = (
        "\\subsection*{Cluster Homogeneity Diagnostics "
        "(\\textcite{carter2017asymptotic}; \\textcite{imbens2016robust})}\n\n"
        "The effective number of clusters $G^*$ collapses the nominal group "
        "count by the degree of cluster-size imbalance:\n"
        "\\[ G^* = \\frac{G}{1 + \\mathrm{cv}^2} \\]\n\n"
        "\\begin{table}[htbp]\n"
        "\\centering\n"
        "\\caption{Cluster Homogeneity Summary}\n"
        "\\label{tab:cluster_diag}\n"
        "\\begin{tabular}{lc}\n"
        "\\toprule\n"
        "Statistic & Value \\\\\n"
        "\\midrule\n"
        f"Nominal clusters ($G$) & {G} \\\\\n"
        f"Mean obs.\\ per cluster ($\\bar{{N}}_g$) & {mean_Ng:,.1f} \\\\\n"
        f"Std.\\ dev.\\ of cluster size ($\\sigma_{{N_g}}$) & {std_Ng:,.1f} \\\\\n"
        f"Coefficient of variation ($\\mathrm{{cv}}$) & {cv:.3f} \\\\\n"
        f"Effective clusters ($G^*$) & {G_star:.2f} \\\\\n"
        f"Total observations & {total:,} \\\\\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
        "\\end{table}\n\n"
        "\\begin{table}[htbp]\n"
        "\\centering\n"
        "\\caption{Top-5 Conglomerates by Observation Share}\n"
        "\\label{tab:top5_clusters}\n"
        "\\begin{tabular}{lcc}\n"
        "\\toprule\n"
        "Conglomerate & Observations & Share \\\\\n"
        "\\midrule\n"
        f"{top5_rows}\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
        "\\end{table}\n\n"
        f"Because $G^* \\approx {G_star:.2f} < 10$, standard cluster-robust "
        "variance estimators (CR1) and Wild Cluster Bootstrap inference "
        "systematically over-reject. All inference below is conducted using "
        "a $t$-distribution with $df = G^*$ following "
        "\\textcite{imbens2016robust} and \\textcite{carter2017asymptotic}. \\\\\n"
    )
    return block, G, G_star


