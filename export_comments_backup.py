# 1. LaTeX Translation Functions
# ==============================================================================
def md_to_tex_string(md_text):
    """
    Minimalistic markdown-to-LaTeX converter with math safeguards.
    Isolates math regions to prevent erroneous character escaping inside
    display or inline math environments.
    """
    blocks = md_text.split('$$')
    processed_blocks = []

    for i, block in enumerate(blocks):
        if i % 2 == 1:
            # Inside block math — emit as display math unchanged
            processed_blocks.append(f"\\[ {block} \\]")
        else:
            # Outside block math: handle inline math then escape
            inline_parts = block.split('$')
            processed_inline = []
            for j, ipart in enumerate(inline_parts):
                if j % 2 == 1:
                    processed_inline.append(f"${ipart}$")
                else:
                    escaped = (ipart
                               .replace('&', '\\&')
                               .replace('%', '\\%')
                               .replace('#', '\\#')
                               .replace('_', '\\_'))
                    processed_inline.append(escaped)
            processed_blocks.append("".join(processed_inline))

    tex = "".join(processed_blocks)

    lines = tex.split('\n')
    out_lines = []
    in_code = False

    for line in lines:
        if line.startswith('```'):
            if in_code:
                out_lines.append('\\end{lstlisting}')
            else:
                out_lines.append('\\begin{lstlisting}')
            in_code = not in_code
            continue

        if in_code:
            out_lines.append(line)
            continue

        if line.startswith('# '):
            out_lines.append(f"\\section*{{{line[2:]}}}")
        elif line.startswith('## '):
            out_lines.append(f"\\subsection*{{{line[3:]}}}")
        elif line.startswith('### '):
            out_lines.append(f"\\subsubsection*{{{line[4:]}}}")
        elif line.startswith('- '):
            out_lines.append(f"\\textbullet\\ {line[2:]} \\\\")
        elif line.strip() == '':
            out_lines.append("\n\n")
        else:
            out_lines.append(line + " \\\\")

    return '\n'.join(out_lines)


