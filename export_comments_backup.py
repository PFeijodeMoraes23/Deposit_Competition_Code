# 2. Booktabs Regression Table Builder
# ==============================================================================
def build_reg_table(res, spec_name, G_nominal, G_star):
    """
    Produces a standalone booktabs LaTeX table from a statsmodels OLS result.

    Parameters
    ----------
    res : statsmodels RegressionResults
    spec_name : str
        Human-readable specification label used as the table caption.
    G_nominal : int
        Nominal number of clusters in this specification.
    G_star : float
        Effective cluster count (Carter et al. 2017).

    Returns
    -------
    str : LaTeX fragment containing the table environment.
    """
    params    = res.params
    bse       = res.bse
    tvalues   = res.tvalues
    pvalues   = res.pvalues
    conf      = res.conf_int()
    nobs      = int(res.nobs)
    rsq       = res.rsquared

    def stars(p):
        if p < 0.01:
            return '***'
        elif p < 0.05:
            return '**'
        elif p < 0.10:
            return '*'
        return ''

    # Variable name prettifier
    def pretty(name):
        name = name.replace('_', '\\_').replace('interaction\\_', '')
        return name

    rows = []
    for var in params.index:
        coef = params[var]
        se   = bse[var]
        p    = pvalues[var]
        s    = stars(p)
        rows.append(
            f"    {pretty(var)} & ${coef:.4f}^{{{s}}}$ & $({se:.4f})$ & ${p:.3f}$ \\\\"
        )

    body = '\n'.join(rows)

    table = (
        f"\\begin{{table}}[htbp]\n"
        f"\\centering\n"
        f"\\caption{{{spec_name}}}\n"
        f"\\label{{tab:{spec_name.replace(' ', '_').replace('/', '').replace(':', '')}}}\n"
        f"\\begin{{tabular}}{{lccc}}\n"
        f"\\toprule\n"
        f"Variable & Coefficient & (Std.\\ Error) & $p$-value \\\\\n"
        f"\\midrule\n"
        f"{body}\n"
        f"\\midrule\n"
        f"\\multicolumn{{4}}{{l}}{{\\footnotesize Obs: {nobs:,} "
        f"\\quad $G = {G_nominal}$ "
        f"\\quad $G^* = {G_star:.2f}$ "
        f"\\quad $R^2 = {rsq:.4f}$}} \\\\\n"
        f"\\multicolumn{{4}}{{l}}{{\\footnotesize "
        f"SEs clustered by prudential conglomerate. "
        f"Inference based on $t_{{G^*}}$ (\\textcite{{imbens2016robust}}; "
        f"\\textcite{{carter2017asymptotic}}).}} \\\\\n"
        f"\\bottomrule\n"
        f"\\end{{tabular}}\n"
        f"\\end{{table}}\n"
    )
    return table


