"""
make_polfunc_md_table.py
========================
Regenerate a policy-function results section of `counterfactuals_plan.md` from the
BBL Step-1 estimation summary JSON. Reproducible counterpart of the paper fragments
`polfunc_k{4,5}.tex` / `polfunc_rate_k{4,5}.tex` (written by
bbl_polfunc.py). Reads the CURRENT .md, replaces the block between
sentinels, and writes the WHOLE .md back (narrative untouched).

Two variants, keyed by --depvar (matching the estimator's --depvar):
    spread : §2.6, LHS = compounded annual deposit spread (1+r^f)^4-(1+r^dep)^4 (the policy fed
             to Step 2), k=4 in percentage points and k=5 in basis points   [default]
    rate   : §2.7, LHS = annualized deposit rate (1+rate_qoq)^4-1

    python make_polfunc_md_table.py                  # spread
    python make_polfunc_md_table.py --depvar rate    # deposit rate

The policy function is SPEC-INVARIANT, so neither the estimator nor these outputs carry a
sleepiness-spec label.
"""
