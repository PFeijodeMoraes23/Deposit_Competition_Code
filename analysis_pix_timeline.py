def tbl_mandatory_institutions(mand_df):
    df = mand_df.copy()
    if "mandatory_since" in df.columns:
        df["Mandatory since"] = pd.to_datetime(df["mandatory_since"], errors="coerce").dt.strftime("%Y-%m-%d")
    if "entry_month_keys" in df.columns:
        df["First key month"] = df["entry_month_keys"].apply(
            lambda x: (f"{int(float(x))//100}-{int(float(x))%100:02d}"
                       if pd.notna(x) and str(x) not in ("nan", "") else "—"))
    if "months_to_join" in df.columns:
        df["Months to join"] = df["months_to_join"].apply(
            lambda x: str(int(x)) if pd.notna(x) else "—")
    out = df.rename(columns={"nome": "Institution", "tipo_instituicao": "Type", "first_spi": "SPI mode"})
    display_cols = ["Institution", "Type", "Mandatory since", "First key month", "Months to join", "SPI mode"]
    return out[[c for c in display_cols if c in out.columns]]


def write_section_inplace(section_md: str):
    """Insert/replace the analysis section inside MAIN_MD between marker comments.
    Idempotent: re-running refreshes the block in place — no separate file is left."""
    with open(MAIN_MD, encoding="utf-8") as f:
        doc = f.read()
    block = f"{MARK_START}\n\n{section_md}\n\n{MARK_END}"
    if MARK_START in doc and MARK_END in doc:
        pre  = doc[:doc.index(MARK_START)]
        post = doc[doc.index(MARK_END) + len(MARK_END):]
        doc  = pre + block + post
    else:
        doc = doc.rstrip() + "\n\n---\n\n" + block + "\n"
    with open(MAIN_MD, "w", encoding="utf-8") as f:
        f.write(doc)


