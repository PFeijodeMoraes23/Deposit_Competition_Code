def tbl_entry_cohort(entry, tcl):
    m = entry.merge(tcl[["ispb", "mv"]], left_on="ISPB", right_on="ispb", how="left")
    m["mv"] = m["mv"].fillna("Unclassified")
    m["year"] = (pd.to_numeric(m["entry_anomes"], errors="coerce") // 100).astype("Int64")
    t = (m.groupby(["year", "mv"]).size().unstack(fill_value=0))
    for c in ["Obrigatória (mandatory)", "Facultativa (voluntary)", "Unclassified"]:
        if c not in t.columns: t[c] = 0
    t = t[["Obrigatória (mandatory)", "Facultativa (voluntary)", "Unclassified"]]
    t["Total"] = t.sum(axis=1)
    t.loc["All years"] = t.sum()
    return t.reset_index().rename(columns={"year": "Entry year"})


def tbl_launch_snapshot(hist):
    h = hist.dropna(subset=["roster_date"])
    with_mv = h[h["tipo_pix"].notna()]
    if with_mv.empty:
        return None, None
    first_date = with_mv["roster_date"].min()
    snap = with_mv[with_mv["roster_date"] == first_date]
    t = (snap.groupby(["tipo_pix", "spi"])["inst_id"].nunique().unstack(fill_value=0))
    t.index = t.index.map({"obrigatoria": "Obrigatória", "facultativa": "Facultativa"})
    t.columns = [c.capitalize() for c in t.columns]
    t["Total"] = t.sum(axis=1); t.loc["Total"] = t.sum()
    return t.reset_index().rename(columns={"index": "Tipo Pix", "tipo_pix": "Tipo Pix"}), first_date.date()


def tbl_top_holders(cur, last):
    tot = cur["qtd_chaves"].sum()
    t = cur.sort_values("qtd_chaves", ascending=False).head(10).copy()
    t["Share %"] = (100 * t["qtd_chaves"] / tot).round(1)
    t["Keys"] = t["qtd_chaves"].map(lambda v: f"{int(v):,}")
    t["Type"] = t["mv"].str.replace(r"\s*\(.*\)", "", regex=True)
    out = t[["Nome", "Keys", "Share %", "Type"]].rename(columns={"Nome": "Institution"})
    out.insert(0, "#", range(1, len(out) + 1))
    return out, last, f"{int(tot):,}"


def tbl_coverage(entry, tcl, hist):
    keys_ispb = set(entry["ISPB"])
    ros_ispb = set(tcl["ispb"].dropna().astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(8))
    both = keys_ispb & ros_ispb
    rows = [
        ("Institutions with key-based entry date (scrape_6)", len(keys_ispb)),
        ("Institutions on ≥1 roster (scrape_7)", hist["inst_id"].nunique()),
        ("Roster institutions matched to an ISPB", len(ros_ispb)),
        ("Matched in BOTH key panel and roster", len(both)),
        ("Key panel only (no roster match)", len(keys_ispb - ros_ispb)),
        ("Classified mandatory/voluntary (ever)", int(tcl["mv"].isin(
            ["Obrigatória (mandatory)", "Facultativa (voluntary)"]).sum())),
    ]
    return pd.DataFrame(rows, columns=["Coverage metric", "Count"])


def build_deposit_classification(tl):
    """Join Pix classification to deposits_panel; aggregate by Year × Quarter × class."""
    list_files = sorted(glob.glob(os.path.join(IF_LIST_DIR, "IF_DATA_List_*.csv")))
    frames = []
    for fp in list_files:
        try:
            df = pd.read_csv(fp, dtype=str,
                             usecols=["CodInst", "CodConglomeradoPrudencial", "CnpjInstituicaoLider"])
            frames.append(df.dropna(subset=["CodConglomeradoPrudencial"]))
        except Exception:
            pass
    iflist = pd.concat(frames, ignore_index=True).drop_duplicates()

    # cnpj8 root → CodConglomeradoPrudencial (primary: leader CNPJ; secondary: CodInst)
    cong_map = {}
    for _, row in iflist.dropna(subset=["CnpjInstituicaoLider"]).iterrows():
        c8 = cnpj8_root(row["CnpjInstituicaoLider"])
        if c8:
            cong_map[c8] = str(row["CodConglomeradoPrudencial"])
    for _, row in iflist.dropna(subset=["CodInst"]).iterrows():
        c8 = cnpj8_root(row["CodInst"])
        if c8 and c8 not in cong_map:
            cong_map[c8] = str(row["CodConglomeradoPrudencial"])

    t = tl.copy()
    t["ispb"] = t["ispb"].astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(8)
    t["cnpj8_r"] = t["cnpj"].apply(cnpj8_root)
    t["cong"] = t["cnpj8_r"].map(cong_map)
    t["ever_mandatory"] = t["ever_mandatory"].astype(str).str.lower().isin(["true", "1"])

    # One row per conglomerate; if conflict keep mandatory
    cong_cls = (t.dropna(subset=["cong"])
                .sort_values("ever_mandatory", ascending=False)
                .drop_duplicates("cong")[["cong", "ever_mandatory"]])
    cong_cls["class"] = cong_cls["ever_mandatory"].map({True: "Mandatory", False: "Voluntary"})

    dep = pd.read_csv(DEPOSITS_CSV, dtype={"CodConglomeradoPrudencial": str})
    dep_cols = [c for c in ["dep_a1", "dep_a2", "dep_a3", "dep_a4", "dep_a5", "dep_outros"]
                if c in dep.columns]
    for c in dep_cols:
        dep[c] = pd.to_numeric(dep[c], errors="coerce")
    dep["dep_total"] = dep[dep_cols].sum(axis=1)

    dep2 = dep.merge(cong_cls[["cong", "class"]],
                     left_on="CodConglomeradoPrudencial", right_on="cong", how="left")
    dep2["class"] = dep2["class"].fillna("Not matched to Pix")

    agg = dep2.groupby(["Year", "Quarter", "class"])["dep_total"].sum().reset_index()
    agg.to_csv(DEPCLASS_CSV, index=False)
    logging.info(f"Saved deposit classification -> {DEPCLASS_CSV} ({len(agg)} rows)")
    n_mand = int(cong_cls["ever_mandatory"].sum())
    n_vol  = int((~cong_cls["ever_mandatory"]).sum())
    return agg, n_mand, n_vol


def build_mandatory_export(tl, hist):
    """Build per-ISPB table for mandatory institutions with time flags."""
    # First roster date per institution with obrigatoria status
    mand_hist = hist[hist["tipo_pix"] == "obrigatoria"].copy()
    first_mand = (mand_hist.groupby("ispb_filled")["roster_date"]
                  .min().reset_index()
                  .rename(columns={"roster_date": "mandatory_since", "ispb_filled": "ispb"}))
    first_mand["ispb"] = first_mand["ispb"].astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(8)

    t = tl.copy()
    t["ispb"] = t["ispb"].astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(8)
    t["ever_mandatory"] = t["ever_mandatory"].astype(str).str.lower().isin(["true", "1"])
    mand = t[t["ever_mandatory"]].copy()

    out = mand.merge(first_mand, on="ispb", how="left")

    def months_diff(row):
        try:
            ms_ts = pd.Timestamp(row["mandatory_since"])
            km_int = int(float(row["entry_month_keys"]))
            km_ts = pd.Timestamp(f"{km_int // 100}-{km_int % 100:02d}-01")
            return (km_ts.year - ms_ts.year) * 12 + (km_ts.month - ms_ts.month)
        except Exception:
            return None

    out["months_to_join"] = out.apply(months_diff, axis=1)

    cols = ["ispb", "nome", "cnpj", "tipo_instituicao",
            "mandatory_since", "entry_month_keys", "months_to_join",
            "first_spi", "last_spi"]
    out = out[[c for c in cols if c in out.columns]].sort_values("mandatory_since")
    out.to_csv(MAND_CSV, index=False)
    logging.info(f"Saved mandatory export -> {MAND_CSV} ({len(out)} rows)")
    return out


